from datetime import datetime
from typing import Protocol

from .entities import Ballot, HelpRequest, HelpStatus, Survey, SurveyId


class SurveyRepository(Protocol):
    def get(self, survey_id: SurveyId) -> Survey | None: ...
    def create_once(self, survey: Survey, creator_receipt: str | None) -> Survey | None: ...
    def add_ballot(self, survey_id: SurveyId, receipt: str, ballot: Ballot) -> bool: ...
    def delete(self, survey_id: SurveyId) -> None: ...


class HelpRepository(Protocol):
    def add_once(self, request: HelpRequest) -> bool: ...
    def transition(self, request_id: str, status: HelpStatus, now: datetime) -> None: ...
    def purge_closed(self, cutoff: datetime) -> int: ...


class HelpNotificationGateway(Protocol):
    def request_received(self, request_id: str) -> None: ...


class SecretGateway(Protocol):
    def encode(self, secret: str) -> str: ...
    def matches(self, secret: str, encoded: str) -> bool: ...


class Clock(Protocol):
    def now(self) -> datetime: ...
